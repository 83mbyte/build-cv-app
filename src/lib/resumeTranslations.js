export const useResumeTranslation = () => {
    const resumeLanguage = useSelector(state => state.editorSettings.resumeLanguage || 'en');
    const t = (key) => {
        return resumeTranslations[resumeLanguage]?.[key]
            || resumeTranslations['en']?.[key]
            || key;
    };
    return { t, resumeLanguage };
};
